import io, re, glob, hashlib, sys

GO = '--go' in sys.argv

def hanzi(t):
    return len(re.findall(r'[\u4e00-\u9fff]', t))

def load(p):
    raw = io.open(p, 'rb').read().decode('utf-8')
    eol = '\r\n' in raw
    return raw.replace('\r\n', '\n'), eol

def save(p, txt, eol):
    out = txt.replace('\n', '\r\n') if eol else txt
    if GO:
        io.open(p, 'wb').write(out.encode('utf-8'))

